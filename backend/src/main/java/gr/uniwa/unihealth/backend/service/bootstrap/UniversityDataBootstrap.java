  private UniGroup saveGroup(String name, String description) {
    UniGroup group = new UniGroup();
    group.setName(name.replace("\n", " ").trim());
    group.setDescription(description.replace("\n", " ").trim());
    group.setActive(true);
    return groupRepository.save(group);
  }

  private void saveDepartment(UniGroup group, String name, String description) {
    Department department = new Department();
    department.setName(name.replace("\n", " ").trim());
    department.setDescription(description.replace("\n", " ").trim());
    department.setActive(true);
    department.setGroup(group);
    departmentRepository.save(department);
  }

